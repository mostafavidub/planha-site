export const serviceDesignQuestions: Record<string, DesignQuestion[]> = {
  'طراحی مکانیک': mechanical,
  'طراحی برق': electrical,
};

export function questionsForService(service: string): DesignQuestion[] {
  const needs = (orderNeeds[service] || []).map((question) => ({
    ...question,
    group: 'نیازهای سفارش' as const,
  }));
  const technical = [
    ...commonDesignQuestions,
    ...(serviceDesignQuestions[service] || []),
  ].map((question) => ({
    ...question,
    group: 'ورودی‌های فنی موتور طراحی' as const,
  }));
  return [...needs, ...technical];
}
